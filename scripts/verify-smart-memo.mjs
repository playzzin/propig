import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdtempSync, rmSync } from 'node:fs';
import path from 'node:path';
import os from 'node:os';
const root = process.env.PROPIG_ROOT || process.cwd();
const runtime = process.env.PROPIG_TEST_RUNTIME || root;
const require = createRequire(path.join(runtime, 'package.json'));
const { build } = require('esbuild');
const temp = mkdtempSync(path.join(os.tmpdir(), 'propig-smart-memo-test-'));
try {
  await build({ entryPoints: [path.join(root, 'src/utils/smartMemo.ts'), path.join(root, 'src/types/stickyNote.ts')], outdir: temp, outbase: path.join(root, 'src'), bundle: true, platform: 'node', format: 'cjs', outExtension: { '.js': '.cjs' } });
  const { toChecklist, checklistContent, normalizeSmartMemoPatch, filterSmartMemos, isReminderDue } = require(path.join(temp, 'utils/smartMemo.cjs'));
  const { StickyNoteSchema } = require(path.join(temp, 'types/stickyNote.cjs'));
  const legacy = { id: 'legacy', content: '회의\n준비\n[x] 검토', x: 120, y: 120, w: 280, h: 240, zIndex: 1, color: 'sun', tags: [], isPinned: false, isArchived: false, createdAt: 1, updatedAt: 2 };
  assert.ok(StickyNoteSchema.safeParse(legacy).success);
  let id = 0;
  const checklist = { ...legacy, ...toChecklist(legacy, () => `item-${++id}`) };
  assert.equal(checklist.checklistItems.length, 2);
  assert.equal(checklist.checklistItems[1].isChecked, true);
  checklist.checklistItems[0].comments.push({ id: 'comment', text: '중요한 설명', createdAt: 1 });
  checklist.content = checklistContent('회의', checklist.checklistItems);
  assert.ok(StickyNoteSchema.safeParse(checklist).success);
  const roundtrip = toChecklist({ ...checklist, memoType: 'text' }, () => `item-${++id}`);
  assert.deepEqual(roundtrip.checklistItems, checklist.checklistItems);
  assert.equal(normalizeSmartMemoPatch(checklist, { content: '스티커에서 변경' }).memoType, 'text');
  assert.deepEqual(normalizeSmartMemoPatch(checklist, { color: 'sky' }), { color: 'sky' });
  const removedText = toChecklist({ ...checklist, content: '회의\n새 내용' }, () => `item-${++id}`);
  assert.ok(removedText.checklistItems.some(item => item.comments.some(comment => comment.text === '중요한 설명')));
  console.log('PASS legacy schema, text/checklist conversion, checked state, comment preservation, legacy editor compatibility');
  const notes = [legacy, { ...checklist, id: 'check', tags: ['업무'], isPinned: true }, { ...legacy, id: 'other', content: '가나다', tags: ['개인'] }];
  assert.equal(filterSmartMemos(notes, '중요한 설명', '', 'all', false, 'updated_desc')[0].id, 'check');
  assert.equal(filterSmartMemos(notes, '', '업무', 'checklist', false, 'title_asc').length, 1);
  assert.equal(filterSmartMemos(notes, '', '__unfiled', 'all', false, 'updated_desc').length, 1);
  assert.equal(filterSmartMemos(notes, '', '', 'text', true, 'title_asc').length, 0);
  assert.equal(filterSmartMemos(notes, '', '', 'all', false, 'title_asc')[0].id, 'check');
  assert.equal(filterSmartMemos([{ ...legacy, tags: ['Work'] }, { ...legacy, id: 'lower', tags: ['work'] }], '', 'WORK', 'all', false, 'updated_desc').length, 2);
  assert.equal(isReminderDue({ ...legacy, reminderAt: 100 }, 101), true);
  assert.equal(isReminderDue({ ...legacy, reminderAt: 100, reminderAcknowledgedAt: 100 }, 101), false);
  assert.equal(isReminderDue({ ...legacy, reminderAt: null }, 101), false);
  assert.equal(StickyNoteSchema.safeParse({ ...legacy, reminderAt: NaN }).success, false);
  console.log('PASS category/type/comment search, pin-first title sorting, reminder due/acknowledge and invalid date');
} finally { rmSync(temp, { recursive: true, force: true }); }
